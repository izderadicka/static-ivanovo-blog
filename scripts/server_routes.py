"""Nginx maps for retained WordPress IDs and legacy query parameters."""
import json


def nginx_files(articles):
    entries = '\n'.join('    ' + a['id'] + ' ' + json.dumps(a['path']) + ';' for a in articles if a['ready'])
    maps = ('# Generated by the site build; included at nginx http scope.\n'
            'map $args $wp_legacy_id {\n    default $arg_page_id;\n    ~(^|&)p= $arg_p;\n}\n'
            'map $wp_legacy_id $wp_legacy_path {\n    default "";\n' + entries + '\n}\n'
            'map $args $wp_has_query {\n    default 0;\n    ~(^|&)(p|page_id)= 1;\n}\n')
    # Named captures avoid clashes with numeric captures used in other nginx maps.
    for key, source, target in [('p', '$args', '$wp_without_p'),
                                ('page_id', '$wp_without_p', '$wp_remaining_args')]:
        maps += (f'map {source} {target} {{\n    default {source};\n'
                 f'    ~^{key}=[^&]*&?(?<{key}_tail>.*)$ ${key}_tail;\n'
                 f'    ~^(?<{key}_before>.+)&{key}=[^&]*&(?<{key}_after>.*)$ "${key}_before&${key}_after";\n'
                 f'    ~^(?<{key}_prefix>.+)&{key}=[^&]*$ ${key}_prefix;\n}}\n')
    maps += ('map $wp_remaining_args $wp_query {\n    default "?$wp_remaining_args";\n    "" "";\n}\n')
    return {'redirects/nginx-maps.conf': maps.encode()}
